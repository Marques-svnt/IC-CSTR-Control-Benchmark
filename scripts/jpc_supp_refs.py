r"""Numbers of the Supplementary Material items cited by the JPC main text, read from the .aux.

The main text and the supplement are separate PDFs, so `\ref` cannot cross between them in the
journal's build. This script reads the labels of `supplementary.aux` and writes
`generated/supprefs.tex`, which defines `\suppref{<label>}` (e.g. `\suppref{tab:rate_demand}` ->
`S10`). An unknown label stops the LaTeX run instead of printing an empty reference.

Usage (after compiling the supplement):
    .venv/bin/python scripts/jpc_supp_refs.py
"""

from __future__ import annotations

import re
from pathlib import Path

PAPER = Path(__file__).resolve().parent.parent / "papers" / "01_journal_of_process_control"
LABEL = re.compile(r"\\newlabel\{([^}]*)\}\{\{([^}]*)\}")


def main() -> None:
    """Writes generated/supprefs.tex from supplementary.aux."""
    aux = (PAPER / "supplementary.aux").read_text(encoding="utf-8")
    labels = {k: v for k, v in LABEL.findall(aux) if v.startswith("S")}
    if not labels:
        raise ValueError("no S-numbered labels in supplementary.aux; compile the supplement first")
    lines = [
        "% Generated by scripts/jpc_supp_refs.py from supplementary.aux -- do not edit.",
        r"\makeatletter",
        r"\newcommand{\suppref}[1]{\@ifundefined{supp@#1}"
        r"{\errmessage{Unknown supplementary label #1}}{\@nameuse{supp@#1}}}",
        *(rf"\@namedef{{supp@{k}}}{{{v}}}" for k, v in sorted(labels.items())),
        r"\makeatother",
    ]
    (PAPER / "generated" / "supprefs.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(labels)} supplementary labels")


if __name__ == "__main__":
    main()
